SELECT le.id, le.entry_key, COUNT(DISTINCT lf.id) AS forms,
       COUNT(DISTINCT i.id) AS inflections,
       COUNT(DISTINCT ro.id) AS outgoing_relations,
       COUNT(DISTINCT ri.id) AS incoming_relations,
       COUNT(DISTINCT ic.id) AS features,
       COUNT(DISTINCT ch.id) AS connector_helps
FROM lexical_entry le
LEFT JOIN lexical_form lf ON lf.entry_id=le.id
LEFT JOIN inflected_form i ON i.lexical_form_id=lf.id
LEFT JOIN form_relation ro ON ro.source_form_id=lf.id
LEFT JOIN form_relation ri ON ri.target_form_id=lf.id
LEFT JOIN ic_feature ic ON ic.form_id=lf.id
LEFT JOIN connector_help ch ON ch.lexical_entry_id=le.id
